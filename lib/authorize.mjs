// Runs before any checkout: no repository or comment code executes. Reads
// structured event data only and fails closed on API errors or insufficient
// repository permission.

// The exact command, alone or followed by exactly the Claude Code attribution
// footer. PR-Agent ignores the footer words (none is a `--key=value` setting);
// any other trailing text could change PR-Agent settings, so it is rejected.
const FOOTER =
  /\n\n---\n_Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code(?:\/session_[A-Za-z0-9]+)?\)_$/;

// Returns the command line when the body is exactly one allowed command,
// optionally followed by the footer; otherwise null.
export function matchCommand(body, pattern) {
  if (typeof body !== "string") return null;
  const normalized = body.replace(/\r\n/g, "\n");
  const trimmed = normalized.trimEnd();
  const command = FOOTER.test(trimmed) ? trimmed.replace(FOOTER, "") : normalized;
  return pattern.test(command) ? command : null;
}

export function isReviewCommand(body) {
  return matchCommand(body, /^\/review$/) !== null;
}

const permitted = async (github, context, username) => {
  const { data } = await github.rest.repos.getCollaboratorPermissionLevel({
    ...context.repo,
    username,
  });
  return { data, ok: ["write", "maintain", "admin"].includes(data.permission) };
};

export async function authorize({
  context,
  github,
  core,
  acknowledge = false,
  runAttempt = process.env.GITHUB_RUN_ATTEMPT,
}) {
  const event = context.payload;
  const author = event?.comment?.user;
  if (
    context.eventName !== "issue_comment" ||
    event.action !== "created" ||
    !event.issue?.pull_request ||
    !isReviewCommand(event.comment?.body) ||
    author?.type !== "User" ||
    !Number.isSafeInteger(author?.id) ||
    author.id <= 0 ||
    // A rerun is never a new authorization to spend.
    Number(runAttempt) !== 1
  ) {
    core.setOutput("allowed", "false");
    return false;
  }
  let allowed;
  try {
    const { data } = await github.rest.repos.getCollaboratorPermissionLevel({
      ...context.repo,
      username: author.login,
    });
    // Bind the API principal to the original author, even after login renames.
    allowed =
      data.user?.id === author.id && ["write", "maintain", "admin"].includes(data.permission);
  } catch {
    core.setOutput("allowed", "false");
    core.setFailed("Cannot confirm the original commenter permission; no paid review.");
    return false;
  }
  core.setOutput("allowed", String(allowed));
  if (!allowed) {
    core.notice("PR-Agent requires repository write permission.");
    return false;
  }
  if (acknowledge) {
    try {
      await github.rest.reactions.createForIssueComment({
        ...context.repo,
        comment_id: event.comment.id,
        content: "eyes",
      });
    } catch {
      core.warning("Could not add the acknowledgement reaction.");
    }
  }
  return true;
}

// Renewal triggers: the schedule, a write-permitted dispatcher, or a human
// write-permitted PR comment of exactly /review-policy or
// /review-policy-resume <run id>. Outputs allowed and resume_run_id.
export async function authorizeRenewal({
  context,
  github,
  core,
  resumeInput = "",
  runAttempt = process.env.GITHUB_RUN_ATTEMPT,
}) {
  const deny = () => {
    core.setOutput("allowed", "false");
    core.setOutput("resume_run_id", "");
    return { allowed: false };
  };
  if (Number(runAttempt) !== 1) return deny();
  let username;
  let resume = "";
  if (context.eventName === "schedule") {
    core.setOutput("allowed", "true");
    core.setOutput("resume_run_id", "");
    return { allowed: true };
  }
  if (context.eventName === "workflow_dispatch") {
    resume = String(resumeInput ?? "");
    if (resume !== "" && !/^[1-9][0-9]{0,19}$/.test(resume)) return deny();
    username = context.actor;
  } else if (context.eventName === "issue_comment") {
    const event = context.payload;
    const author = event?.comment?.user;
    const command = matchCommand(
      event?.comment?.body,
      /^\/review-policy(?:-resume [1-9][0-9]{0,19})?$/,
    );
    if (
      event.action !== "created" ||
      !event.issue?.pull_request ||
      command === null ||
      author?.type !== "User" ||
      !Number.isSafeInteger(author?.id)
    )
      return deny();
    resume = command.split(" ")[1] ?? "";
    username = author.login;
  } else return deny();
  try {
    const { data, ok } = await permitted(github, context, username);
    const bound =
      context.eventName !== "issue_comment" || data.user?.id === context.payload.comment.user.id;
    if (!ok || !bound) {
      core.notice("Reviewer renewal requires repository write permission.");
      return deny();
    }
  } catch {
    core.setFailed("Cannot confirm the requester's permission; no renewal.");
    return deny();
  }
  core.setOutput("allowed", "true");
  core.setOutput("resume_run_id", resume);
  return { allowed: true, resume };
}
