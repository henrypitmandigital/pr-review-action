import assert from "node:assert/strict";
import { test } from "node:test";
import { authorize, isReviewCommand } from "./authorize.mjs";

const event = () => ({
  eventName: "issue_comment",
  repo: { owner: "o", repo: "r" },
  payload: {
    action: "created",
    issue: { pull_request: { url: "https://api.github.com/repos/o/r/pulls/1" } },
    comment: {
      id: 77,
      body: "/review",
      user: { login: "original-author", type: "User", id: 123 },
    },
    sender: { login: "different-sender" },
  },
});
async function check(
  context,
  {
    permission = "write",
    error = false,
    principal = 123,
    runAttempt = "1",
    acknowledge = false,
  } = {},
) {
  const outputs = {};
  const reactions = [];
  let apiCalls = 0;
  let failed = false;
  await authorize({
    context,
    runAttempt,
    acknowledge,
    github: {
      rest: {
        repos: {
          getCollaboratorPermissionLevel: async (args) => {
            apiCalls++;
            assert.equal(args.username, "original-author");
            if (error) throw Error("SECRET provider diagnostic");
            return { data: { permission, user: { id: principal } } };
          },
        },
        reactions: {
          createForIssueComment: async (args) => {
            reactions.push(args);
          },
        },
      },
    },
    core: {
      setOutput: (key, value) => {
        outputs[key] = value;
      },
      notice() {},
      warning() {},
      setFailed: (message) => {
        assert.ok(!message.includes("SECRET"));
        failed = true;
      },
    },
  });
  return { allowed: outputs.allowed, apiCalls, failed, reactions };
}

for (const permission of ["write", "maintain", "admin", "read", "triage", "none", undefined]) {
  test(`native permission ${permission} gates the exact original author`, async () => {
    assert.equal(
      (await check(event(), { permission: permission ?? "unknown" })).allowed,
      ["write", "maintain", "admin"].includes(permission) ? "true" : "false",
    );
  });
}
test("permission lookup errors fail closed without echoing provider data", async () => {
  const { allowed, apiCalls, failed } = await check(event(), { permission: "admin", error: true });
  assert.deepEqual({ allowed, apiCalls, failed }, { allowed: "false", apiCalls: 1, failed: true });
});
for (const body of [
  "/Review",
  "/REVIEW",
  " /review",
  "/review\n",
  "/review please",
  "/describe",
  "ordinary text",
  "/review\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n--model=x",
  "/review\n\n---\n_Generated by [Other](https://claude.ai/code)_",
  "/review\n---\n_Generated by [Claude Code](https://claude.ai/code)_",
  "/review\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_x --model=y)_",
  "/review\n\n---\n_Generated by [Claude Code](https://claude.ai/code/other)_",
]) {
  test(`rejects nonexact command ${JSON.stringify(body)} before API access`, async () => {
    const e = event();
    e.payload.comment.body = body;
    assert.equal((await check(e)).apiCalls, 0);
  });
}
for (const footer of [
  "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_",
  "\r\n\r\n---\r\n_Generated by [Claude Code](https://claude.ai/code)_\n",
  "\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_01ExampleSession000000000)_",
]) {
  test(`accepts /review followed by the exact Claude Code footer ${JSON.stringify(footer)}`, async () => {
    const e = event();
    e.payload.comment.body = `/review${footer}`;
    const { allowed, apiCalls, failed } = await check(e);
    assert.deepEqual(
      { allowed, apiCalls, failed },
      { allowed: "true", apiCalls: 1, failed: false },
    );
  });
}
test("non-string bodies are never commands", () => {
  for (const body of [null, undefined, 1, ["/review"]]) assert.equal(isReviewCommand(body), false);
});
for (const kind of [
  "ordinary-issue",
  "edited",
  "inline",
  "pr-created",
  "push",
  "synchronize",
  "workflow_run",
  "bot",
]) {
  test(`rejects ${kind} without authorization/inference`, async () => {
    const e = event();
    if (kind === "ordinary-issue") delete e.payload.issue.pull_request;
    else if (kind === "edited") e.payload.action = "edited";
    else if (kind === "bot") e.payload.comment.user.type = "Bot";
    else e.eventName = kind === "inline" ? "pull_request_review_comment" : kind;
    assert.equal((await check(e)).apiCalls, 0);
  });
}
test("a reused login cannot authorize a different GitHub principal", async () => {
  assert.equal((await check(event(), { permission: "admin", principal: 456 })).allowed, "false");
  assert.equal((await check(event(), { permission: "admin", principal: null })).allowed, "false");
});
test("a comment missing its original principal fails before the API call", async () => {
  const e = event();
  delete e.payload.comment.user.id;
  assert.equal((await check(e)).apiCalls, 0);
});
test("rerunning a created-comment workflow never buys another review", async () => {
  const result = await check(event(), { runAttempt: "2" });
  assert.deepEqual([result.allowed, result.apiCalls], ["false", 0]);
});
test("acknowledgement reacts only after authorization", async () => {
  assert.deepEqual(
    (await check(event(), { acknowledge: true })).reactions.map((r) => [r.comment_id, r.content]),
    [[77, "eyes"]],
  );
  assert.equal(
    (await check(event(), { acknowledge: true, permission: "read" })).reactions.length,
    0,
  );
  assert.equal((await check(event())).reactions.length, 0);
});
